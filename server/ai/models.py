# ai/models.py — AI Interaction Logging Model for TutorLink.
#
# Logs every Gemini API call (Post Generator, Tutor Recommendation, CV Skill Extraction,
# and upcoming AI Matching Chatbot) for auditing, analytics, and user context.

from django.db import models
from django.conf import settings


class AIInteraction(models.Model):
    """
    Tracks and audits every AI interaction powered by Google Gemini API.
    
    Types:
    - 'post_generator': Tuition post requirement text generation for guardians.
    - 'tutor_recommendation': Contextual tutor ranking and match explanation for a tuition post.
    - 'cv_skill_extraction': PDF CV parsing and skill extraction for tutors.
    - 'chatbot': Conversational tutor matching assistant (Phase G).
    """
    INTERACTION_TYPES = (
        ('post_generator', 'Post Generator'),
        ('tutor_recommendation', 'Tutor Recommendation'),
        ('cv_skill_extraction', 'CV Skill Extraction'),
        ('chatbot', 'Chatbot Interaction'),
    )

    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name='ai_interactions',
        help_text='User who triggered the AI interaction.'
    )
    type = models.CharField(
        max_length=50,
        choices=INTERACTION_TYPES,
        help_text='Category of AI feature invoked.'
    )
    input_text = models.TextField(
        help_text='Input payload / prompt instructions sent to Gemini.'
    )
    output_text = models.TextField(
        help_text='Raw or processed response generated by Gemini.'
    )
    created_at = models.DateTimeField(
        auto_now_add=True,
        help_text='Timestamp when the AI interaction occurred.'
    )

    class Meta:
        ordering = ['-created_at']
        verbose_name = 'AI Interaction'
        verbose_name_plural = 'AI Interactions'

    def __str__(self):
        return f"[{self.type}] {self.user.username} @ {self.created_at.strftime('%Y-%m-%d %H:%M')}"
